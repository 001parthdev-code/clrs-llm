from dataclasses import dataclass


@dataclass
class ModelConfig:
    """
    Configuration for the CLRS-LLM Transformer.
    """

    # ---------------------------------------------------------
    # Vocabulary
    # ---------------------------------------------------------

    vocab_size: int = 8196

    # ---------------------------------------------------------
    # Dataset
    # ---------------------------------------------------------

    context_length: int = 128

    # ---------------------------------------------------------
    # Transformer Architecture
    # ---------------------------------------------------------

    embedding_dim: int = 128
    num_heads: int = 4
    num_layers: int = 4

    # ---------------------------------------------------------
    # Feed Forward Network
    # ---------------------------------------------------------

    ffn_hidden_dim: int = 512

    # ---------------------------------------------------------
    # Regularization
    # ---------------------------------------------------------

    dropout: float = 0.1

    